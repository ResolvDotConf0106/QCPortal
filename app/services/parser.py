import csv
import os
from typing import Dict, Any, List

class QCParser:
    @staticmethod
    def parse_csv_report(csv_file_path: str) -> Dict[str, Any]:
        """
        Parse the QC CSV report file generated by QC.sh.
        Returns a dictionary containing summary stats and list of check items.
        """
        checks: List[Dict[str, Any]] = []
        summary = {
            'total': 0,
            'pass': 0,
            'fail': 0,
            'warn': 0,
            'na': 0,
            'info': 0,
            'score': '0%',
            'hostname': ''
        }

        if not os.path.exists(csv_file_path):
            return {'summary': summary, 'checks': checks}

        with open(csv_file_path, 'r', encoding='utf-8', errors='replace') as f:
            reader = csv.reader(f)
            
            in_summary_section = False
            for row in reader:
                if not row:
                    continue
                
                # Check for header of check items
                if len(row) >= 7 and row[0].strip() == 'Section' and row[6].strip() == 'Status':
                    continue

                # Check for start of summary block at bottom of CSV
                if row[0].strip() == 'Physical Server QC Check Report':
                    in_summary_section = True
                    continue

                if in_summary_section:
                    if len(row) >= 2:
                        key = row[0].strip()
                        val = row[1].strip()
                        if key == 'Hostname':
                            summary['hostname'] = val
                        elif key == 'Total Checks':
                            summary['total'] = int(val) if val.isdigit() else 0
                        elif key == 'PASS':
                            summary['pass'] = int(val) if val.isdigit() else 0
                        elif key == 'FAIL':
                            summary['fail'] = int(val) if val.isdigit() else 0
                        elif key == 'WARNING':
                            summary['warn'] = int(val) if val.isdigit() else 0
                        elif key == 'N/A':
                            summary['na'] = int(val) if val.isdigit() else 0
                        elif key == 'INFO':
                            summary['info'] = int(val) if val.isdigit() else 0
                        elif key == 'Pass Rate':
                            summary['score'] = val
                    continue

                # Normal check row: Section, S.No, Check Item, Command Used, Expected Result, Actual Result, Status, Notes
                if len(row) >= 7:
                    section = row[0].strip()
                    sno_str = row[1].strip()
                    sno = int(sno_str) if sno_str.isdigit() else 0
                    item = row[2].strip()
                    cmd = row[3].strip()
                    expected = row[4].strip()
                    actual = row[5].strip()
                    status = row[6].strip().upper()
                    notes = row[7].strip() if len(row) > 7 else ''

                    checks.append({
                        'section': section,
                        'sno': sno,
                        'check_item': item,
                        'command_used': cmd,
                        'expected': expected,
                        'actual': actual,
                        'status': status,
                        'notes': notes
                    })

                    # If summary block wasn't present, compute live stats
                    if not in_summary_section:
                        summary['total'] += 1
                        if status == 'PASS':
                            summary['pass'] += 1
                        elif status == 'FAIL':
                            summary['fail'] += 1
                        elif status == 'WARNING' or status == 'WARN':
                            summary['warn'] += 1
                        elif status == 'N/A' or status == 'NA':
                            summary['na'] += 1
                        elif status == 'INFO':
                            summary['info'] += 1

        # Calculate score if not parsed from summary block
        if summary['total'] > 0 and summary['score'] == '0%':
            rate = int((summary['pass'] / summary['total']) * 100)
            summary['score'] = f"{rate}%"

        return {
            'summary': summary,
            'checks': checks
        }
